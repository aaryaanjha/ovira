// Generates supabase/setup.sql from the app's schema and starter content.
// Run with: npm run supabase:sql
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { schema, seedStatements, toPostgres } from "../lib/database.mjs";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const tables = ["leads", "appointments", "posts", "myths", "testimonials", "slides", "media", "contact", "socials"];

const literal = value => {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return String(value);
  return "'" + String(value).replace(/'/g, "''") + "'";
};
const inline = ({ sql, params }) => {
  let index = 0;
  return toPostgres(sql).replace(/\$(\d+)/g, () => literal(params[index++]));
};

const createTables = schema.split(";").map(value => value.trim())
  .filter(statement => statement && !statement.toUpperCase().startsWith("PRAGMA "))
  .map(statement => toPostgres(statement) + ";");

const sql = `-- OVIRA database setup for Supabase.
-- Paste this whole file into Supabase Dashboard -> SQL Editor -> New query, then click Run.
-- Safe to run more than once: it never deletes or overwrites existing data.
-- Generated by scripts/supabase-sql.mjs; regenerate with \`npm run supabase:sql\` instead of editing by hand.

begin;

-- 1. Tables
${createTables.join("\n\n")}

-- 2. Additive migrations for databases created by earlier OVIRA versions.
ALTER TABLE public.media ADD COLUMN IF NOT EXISTS "url" TEXT NOT NULL DEFAULT '';

-- 3. Lock tables away from the public Supabase API.
-- The website connects with DATABASE_URL (the postgres role), which is not affected by RLS.
-- With RLS on and no policies, the anon key cannot read leads or appointments.
${tables.map(table => `alter table public.${table} enable row level security;`).join("\n")}

-- 4. Starter content (blog articles, myths, homepage slides, contact details)
${seedStatements().map(statement => inline(statement) + ";").join("\n\n")}

-- 5. Public bucket for images uploaded from the admin panel (JPG, PNG, WebP up to 5 MB)
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('ovira-media', 'ovira-media', true, 5242880, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update set public = true, file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

commit;
`;

mkdirSync(path.join(root, "supabase"), { recursive: true });
writeFileSync(path.join(root, "supabase", "setup.sql"), sql);
console.log("Wrote supabase/setup.sql");
